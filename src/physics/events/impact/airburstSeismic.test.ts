/** The paper's Ms from a peak amplitude and period at 10 000 km (p. 216). */
const DELTA_DEG = 10_000 / 111.19492664455873;
const msOfAmplitude = (a: number, t: number): number =>
  Math.log10((2 * a) / t) + 1.66 * Math.log10(DELTA_DEG) - 0.18;
/** The paper's Ms from its % coupling, by Pomeroy (1963)'s seismic energy. */
const msOfCoupling = (percent: number, kt: number): number => {
  const c = Math.log10((percent / 100) * kt * 4.184e19) - 9.4;
  return (2.14 - Math.sqrt(2.14 * 2.14 - 4 * 0.054 * c)) / (2 * 0.054);
};

const EARTHS: readonly HarkriderEarth[] = ['continental', 'oceanic'];
const cellsOf = (row: PrintedRow, earth: HarkriderEarth) =>
  earth === 'continental'
    ? { a: row[2], t: row[3], ms: row[4], c: row[5] }
    : { a: row[6], t: row[7], ms: row[8], c: row[9] };

/** The three cells of the Ms columns read otherwise than printed. */
const READ_OTHERWISE = new Map<string, number>([
  ['continental 1.8288 10000', 4.79],
  ['continental 10 100', 3.48],
  ['oceanic 0.3048 3', 1.96],
]);

describe('Harkrider, Newton & Flinn (1974), Table 4', () => {
  it('is every row of the scan, on the relation’s nodes', () => {
    expect(PRINTED).toHaveLength(99);
    PRINTED.forEach((row, n) => {
      expect(row[0]).toBe(HARKRIDER_ALTITUDES_KM[Math.floor(n / 9)]);
      expect(row[1]).toBe(HARKRIDER_YIELDS_KT[n % 9]);
    });
  });

  it('holds its own printed Ms, but for three cells two witnesses outvote', () => {
    const amplitudeOutvoted: string[] = [];
    const couplingOutvoted: string[] = [];
    for (const row of PRINTED) {
      for (const earth of EARTHS) {
        const key = `${earth} ${row[0].toString()} ${row[1].toString()}`;
        const { a, t, ms, c } = cellsOf(row, earth);
        const fromAmplitude = msOfAmplitude(a, t);
        const fromCoupling = msOfCoupling(c, row[1]);
        const read = READ_OTHERWISE.get(key);
        const relation =
          HARKRIDER_MS[earth][HARKRIDER_ALTITUDES_KM.indexOf(row[0])]?.[
            HARKRIDER_YIELDS_KT.indexOf(row[1])
          ];
        if (read !== undefined) {
          // The print disagrees with both witnesses, which agree with each other.
          expect(Math.abs(fromAmplitude - fromCoupling), key).toBeLessThan(0.05);
          expect(Math.abs(read - fromAmplitude), key).toBeLessThan(0.01);
          if (ms !== null) expect(Math.abs(ms - fromAmplitude), key).toBeGreaterThan(0.08);
          expect(relation, key).toBe(read);
          continue;
        }
        expect(relation, key).toBe(ms);
        if (ms === null) throw new Error(key);
        if (Math.abs(ms - fromAmplitude) > 0.02) {
          // The amplitude is the misprint: the coupling agrees with the Ms.
          expect(Math.abs(ms - fromCoupling), key).toBeLessThan(0.02);
          amplitudeOutvoted.push(key);
        } else if (Math.abs(ms - fromCoupling) > 0.05) {
          couplingOutvoted.push(key);
        }
      }
    }
    expect(amplitudeOutvoted).toEqual([
      'continental 3.6576 30',
      'continental 4.8768 100',
      'oceanic 66 3000',
      'continental 80 30',
    ]);
    expect(couplingOutvoted).toEqual([
      'continental 0.3048 3',
      'oceanic 0.3048 10',
      'oceanic 0.3048 100',
      'oceanic 3.6576 3',
      'oceanic 3.6576 3000',
      'oceanic 4.8768 300',
      'oceanic 30.7 1',
      'oceanic 30.7 100',
      'oceanic 51.2 100',
      'continental 66 30',
      'oceanic 66 10000',
      'oceanic 80 10',
      'oceanic 80 300',
    ]);
  });

  it('returns the table at its nodes, and nothing outside it', () => {
    for (const earth of EARTHS) {
      HARKRIDER_ALTITUDES_KM.forEach((h, i) => {
        HARKRIDER_YIELDS_KT.forEach((w, j) => {
          expect(harkriderMs(w, h, earth)).toBeCloseTo(HARKRIDER_MS[earth][i]?.[j] ?? NaN, 12);
        });
      });
    }
    expect(harkriderMs(0.99, 10)).toBeNull();
    expect(harkriderMs(10_001, 10)).toBeNull();
    expect(harkriderMs(100, 0.3)).toBeNull();
    expect(harkriderMs(100, 80.1)).toBeNull();
    expect(harkriderMs(Number.NaN, 10)).toBeNull();
    // Linear in altitude, and in the logarithm of the yield.
    expect(harkriderMs(100, (18.6 + 30.7) / 2)).toBeCloseTo((3.82 + 3.78) / 2, 12);
    expect(harkriderMs(Math.sqrt(100 * 300), 18.6)).toBeCloseTo((3.82 + 4.05) / 2, 12);
  });

  it('rises with the yield everywhere but where the peak changes period', () => {
    const falls: string[] = [];
    for (const earth of EARTHS) {
      HARKRIDER_MS[earth].forEach((row, i) => {
        row.forEach((ms, j) => {
          if (j > 0 && ms < (row[j - 1] ?? -Infinity)) {
            falls.push(
              `${earth} ${String(HARKRIDER_ALTITUDES_KM[i])} ${String(HARKRIDER_YIELDS_KT[j - 1])}-${String(HARKRIDER_YIELDS_KT[j])}`
            );
          }
        });
      });
    }
    expect(falls).toEqual(['continental 3.6576 1000-3000', 'continental 4.8768 1000-3000']);
  });
});
