/** Rule 1041: how a body is read by its type. */
export type ThirdSetReading = 'counted' | 'robustnessControl';

/** Rule 1123: one observable's eligibility for a body, with its reason. */
export interface Eligibility {
  readonly eligible: boolean;
  readonly why: string;
}

export interface ThirdSetBody {
  readonly event: string;
  readonly type: string;
  readonly reading: ThirdSetReading;
  readonly inputs: {
    readonly velocity: LevelBInput;
    readonly angle: LevelBInput;
    readonly diameter: LevelBInput;
    readonly density: LevelBInput;
    readonly targetDensity: LevelBInput;
  };
  /** Rule 1121 (e): O1's observed interval (km), and the flares beside it. */
  readonly o1: Eligibility & {
    readonly intervalKm: readonly [number, number];
    readonly flaresKm: readonly number[];
    readonly where: string;
    /** Rule 1125 (b): which peaks enter the interval, which stay out, and why. */
    readonly selection: string;
  };
  /** Rule 1114: O2, diagnostic — the largest recovered mass and its class. */
  readonly o2: {
    readonly largestKg: number;
    readonly class: 'measured' | 'lowerBound';
    readonly where: string;
  };
  readonly o3: Eligibility;
  /** Rule 1109: what the sources document of the ground. */
  readonly ground: {
    readonly recovery: Eligibility;
    readonly noCrater: Eligibility;
    readonly regime: Eligibility;
  };
  /** Rule 1121 (d): contradictions inside the source, recorded. */
  readonly recorded?: readonly string[];
}

