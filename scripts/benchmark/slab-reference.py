#!/usr/bin/env python3
"""Reference medians for the two slab candidates of rule 67 of
src/physics/validation/slabRules.ts, computed with the OpenQuake Engine
(GEM Foundation, AGPL-3.0-or-later): AbrahamsonEtAl2015SSlab (central,
forearc, ergodic) and ParkerEtAl2020SSlab (no region, no basin), median PGA
in g for a point source at the hypocentre, on a grid of magnitudes, depths,
epicentral distances and Vs30. Writes src/physics/validation/slabReference.ts.
Nothing here runs Nimbus.

    <python with openquake.engine installed> scripts/benchmark/slab-reference.py
"""

import math
from pathlib import Path

import numpy as np
from openquake.baselib import __version__ as OQ_VERSION
from openquake.hazardlib.contexts import ContextMaker, RuptureContext
from openquake.hazardlib.gsim.abrahamson_2015 import AbrahamsonEtAl2015SSlab
from openquake.hazardlib.gsim.parker_2020 import ParkerEtAl2020SSlab

ROOT = Path(__file__).resolve().parents[2]
MAGNITUDES = [6.0, 6.5, 7.0, 7.5, 7.8, 8.2]
DEPTHS_KM = [70.5, 100, 150, 220, 300]
EPICENTRAL_KM = [0, 10, 30, 60, 100, 200, 400, 800]
VS30 = [180, 300, 760, 1200]
MODELS = [("abrahamson2016Slab", AbrahamsonEtAl2015SSlab), ("parker2022Slab", ParkerEtAl2020SSlab)]


def medians(cls):
    rows = []
    gsim = cls()
    cm = ContextMaker("*", [gsim], dict(imtls={"PGA": [0]}))
    for mag in MAGNITUDES:
        for depth in DEPTHS_KM:
            for vs30 in VS30:
                rhypo = [math.hypot(x, depth) for x in EPICENTRAL_KM]
                n = len(rhypo)
                ctx = RuptureContext()
                ctx.sids = np.arange(n)
                ctx.mag = float(mag)
                ctx.hypo_depth = float(depth)
                ctx.rake, ctx.dip, ctx.ztor, ctx.width = 90.0, 45.0, float(depth), 20.0
                ctx.vs30 = np.full(n, float(vs30))
                ctx.vs30measured = np.zeros(n, bool)
                ctx.backarc = np.zeros(n, bool)
                ctx.rhypo = np.asarray(rhypo, float)
                ctx.rrup = np.asarray(rhypo, float)
                out = cm.get_mean_stds([ctx])
                for i, r in enumerate(rhypo):
                    rows.append((mag, depth, r, vs30, float(math.exp(out[0, 0, 0, i]))))
    return rows


def main():
    parts = []
    for name, cls in MODELS:
        lines = "\n".join(
            f"    [{mag}, {depth}, {r!r}, {vs30}, {pga!r}]," for mag, depth, r, vs30, pga in medians(cls)
        )
        parts.append(f"  {name}: [\n{lines}\n  ],")
    body = f"""// Generated by scripts/benchmark/slab-reference.py with OpenQuake
// {OQ_VERSION} (GEM Foundation, AGPL-3.0-or-later). Do not edit by hand.

/** OpenQuake's median PGA (g) for each rule 67 candidate: [magnitude,
 *  hypocentre depth (km), hypocentral distance (km), Vs30 (m/s), PGA]. */
// prettier-ignore
export const SLAB_REFERENCE: Readonly<
  Record<'abrahamson2016Slab' | 'parker2022Slab', readonly (readonly [number, number, number, number, number])[]>
> = {{
{chr(10).join(parts)}
}};
"""
    out = ROOT / "src" / "physics" / "validation" / "slabReference.ts"
    out.write_text(body)
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
