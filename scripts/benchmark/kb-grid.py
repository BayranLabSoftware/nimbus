#!/usr/bin/env python3
"""The black-box grid behind rules 177 to 181: an independent implementation of
Kingery–Bulmash asked for the incident pressure of a hemispherical TNT surface
burst, over the charges and distances Nimbus draws rings at.

The relation itself is written in `src/physics/effects/kingeryBulmash.ts` from
Swisdak's (1994) Table 1, and held in CI to the worked examples the United
Nations' IATG 01.80 prints. This script adds what those examples cannot give:
a dense comparison against a second implementation of the same fits, the
MIT-licensed `kingery-bulmash` package (github.com/fcento100/kingery-bulmash),
used as a black box — its answers are read, its code is not.

    python3 scripts/benchmark/kb-grid.py <package checkout> <out.ts>

It writes `src/physics/validation/kingeryBulmashReference.ts`: the package's
answers on the grid, which `kingeryBulmash.test.ts` then holds the model to.
Nothing here runs Nimbus.
"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(Path(sys.argv[1]) / "src"))
import kingery_bulmash as kb  # noqa: E402

# Charges from a hand grenade's filling to a kilotonne, and the scaled
# distances between the package's own lower limit and the 40 m·kg^(-1/3) its
# fits are documented for. The three rings Nimbus draws sit at about 5.3, 18.6
# and 29.7 m·kg^(-1/3), so they are inside it.
CHARGES_KG = [1, 10, 100, 1_000, 10_000, 100_000, 1_000_000, 1_000_000_000]
SCALED_MIN = 0.2
SCALED_MAX = 40.0
SCALED_STEPS = 60

# IATG 01.80 (2021), Table 5: charge (kg), range (m), incident pressure (kPa),
# as the guideline prints them from the original 1984 polynomials.
IATG_TABLE_5 = [(1_000, 50, 43.0), (10_000, 50, 202.0), (100_000, 50, 1_150.0)]


def incident_kpa(neq: float, distance: float) -> float:
    return kb.Blast_Parameters(
        unit_system=kb.Units.METRIC, neq=neq, distance=distance
    ).incident_pressure


def main() -> None:
    checks = []
    for neq, distance, printed in IATG_TABLE_5:
        value = incident_kpa(neq, distance)
        checks.append(
            {
                "chargeKg": neq,
                "rangeM": distance,
                "iatgKpa": printed,
                "packageKpa": value,
                "relative": value / printed - 1,
            }
        )

    rows = []
    for charge in CHARGES_KG:
        cube = charge ** (1 / 3)
        for step in range(SCALED_STEPS + 1):
            scaled = SCALED_MIN * (SCALED_MAX / SCALED_MIN) ** (step / SCALED_STEPS)
            try:
                value = incident_kpa(charge, scaled * cube)
            except Exception as error:  # the package refuses outside its range
                print(f"  skipped charge {charge} kg at Z {scaled:.3f}: {error}")
                continue
            rows.append(
                {"chargeKg": charge, "scaled": round(scaled, 6), "kPa": value}
            )

    out = Path(sys.argv[2])
    header = f"""/* Generated by scripts/benchmark/kb-grid.py — do not edit by hand.
 *
 * The incident pressure of a hemispherical TNT surface burst, as an
 * implementation of Kingery–Bulmash independent of this project answers for it:
 * the MIT-licensed `kingery-bulmash` package (github.com/fcento100/kingery-bulmash),
 * which implements Swisdak's (1994) simplified fits, run as a black box on
 * {len(rows)} points — {len(CHARGES_KG)} charges from 1 kg to 1 kt, at {SCALED_STEPS + 1} scaled
 * distances from {SCALED_MIN} to {SCALED_MAX} m·kg⁻¹ᐟ³ each.
 *
 * Before the grid, the package is held to the three worked examples IATG 01.80
 * (2021) Table 5 prints, which come from the original 1984 polynomials:
 * {', '.join(f"{c['relative'] * 100:+.2f} %" for c in checks)}.
 *
 * `effects/kingeryBulmash.test.ts` holds the model to these points. The model
 * is written from Swisdak's paper (rules 177 to 181 of
 * validation/chemicalBlastRules.ts), not from this package.
 */

export interface KingeryBulmashPoint {{
  /** Charge, in kilogrammes of TNT. */
  readonly chargeKg: number;
  /** Scaled distance, m·kg⁻¹ᐟ³. */
  readonly scaled: number;
  /** Peak incident overpressure, kPa. */
  readonly kPa: number;
}}

/** The package's answer at each point of the grid. */
export const KINGERY_BULMASH_GRID: readonly KingeryBulmashPoint[] = {json.dumps(rows, indent=1)};

/** The package against IATG 01.80 (2021) Table 5, as a fraction. */
export const KINGERY_BULMASH_IATG_CHECK: readonly {{
  readonly chargeKg: number;
  readonly rangeM: number;
  readonly iatgKpa: number;
  readonly packageKpa: number;
  readonly relative: number;
}}[] = {json.dumps(checks, indent=1)};
"""
    out.write_text(header)
    worst = max(abs(c["relative"]) for c in checks)
    print(f"IATG Table 5 worst {worst:.4f}; wrote {len(rows)} points to {out}")


if __name__ == "__main__":
    main()
