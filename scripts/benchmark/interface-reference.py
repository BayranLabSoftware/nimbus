#!/usr/bin/env python3
"""Reference medians for the two interface candidates of rule 36 of
src/physics/validation/interfaceRules.ts, computed with the OpenQuake Engine
(GEM Foundation, AGPL-3.0-or-later): AbrahamsonEtAl2015SInter (central,
forearc, ergodic) and ParkerEtAl2020SInter (no region, no basin), median PGA
in g on a grid of magnitudes, rupture distances and Vs30. Writes
src/physics/validation/interfaceReference.ts. Nothing here runs Nimbus.

    <python with openquake.engine installed> scripts/benchmark/interface-reference.py
"""

import math
from pathlib import Path

import numpy as np
from openquake.baselib import __version__ as OQ_VERSION
from openquake.hazardlib.contexts import ContextMaker, RuptureContext
from openquake.hazardlib.gsim.abrahamson_2015 import AbrahamsonEtAl2015SInter
from openquake.hazardlib.gsim.parker_2020 import ParkerEtAl2020SInter

ROOT = Path(__file__).resolve().parents[2]
MAGNITUDES = [6.0, 6.5, 7.0, 7.5, 7.8, 8.0, 8.2, 8.5, 9.0, 9.5]
RRUP_KM = [1, 2, 5, 10, 20, 30, 50, 75, 100, 150, 200, 300, 500, 750, 1000]
VS30 = [150, 270, 400, 760, 900, 1200, 1500]
MODELS = [("abrahamson2016", AbrahamsonEtAl2015SInter), ("parker2022", ParkerEtAl2020SInter)]


def medians(cls):
    rows = []
    gsim = cls()
    cm = ContextMaker("*", [gsim], dict(imtls={"PGA": [0]}))
    for mag in MAGNITUDES:
        for vs30 in VS30:
            n = len(RRUP_KM)
            ctx = RuptureContext()
            ctx.sids = np.arange(n)
            ctx.mag = float(mag)
            ctx.rake, ctx.dip, ctx.ztor, ctx.width, ctx.hypo_depth = 90.0, 15.0, 10.0, 100.0, 25.0
            ctx.vs30 = np.full(n, float(vs30))
            ctx.vs30measured = np.zeros(n, bool)
            ctx.backarc = np.zeros(n, bool)
            ctx.rrup = np.asarray(RRUP_KM, float)
            out = cm.get_mean_stds([ctx])
            for i, r in enumerate(RRUP_KM):
                rows.append((mag, r, vs30, float(math.exp(out[0, 0, 0, i]))))
    return rows


def main():
    parts = [
        "// Generated by scripts/benchmark/interface-reference.py with OpenQuake",
        f"// {OQ_VERSION} (GEM Foundation, AGPL-3.0-or-later). Do not edit by hand.",
        "",
        "/** OpenQuake's median PGA (g) for each rule 36 candidate: [magnitude,",
        " *  rupture distance (km), Vs30 (m/s), PGA]. */",
        "export const INTERFACE_REFERENCE: Readonly<",
        "  Record<'abrahamson2016' | 'parker2022', readonly (readonly [number, number, number, number])[]>",
        "> = {",
    ]
    for name, cls in MODELS:
        parts.append(f"  {name}: [")
        for mag, r, vs30, pga in medians(cls):
            parts.append(f"    [{mag}, {r}, {vs30}, {pga:.8g}],")
        parts.append("  ],")
    parts.append("};")
    parts.append("")
    parts.append(f"export const INTERFACE_REFERENCE_OPENQUAKE = '{OQ_VERSION}';")
    out = ROOT / "src" / "physics" / "validation" / "interfaceReference.ts"
    out.write_text("\n".join(parts) + "\n")
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
