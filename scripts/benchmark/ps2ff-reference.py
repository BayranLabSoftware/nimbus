#!/usr/bin/env python3
"""Reference averages for the candidate of rule 51 of
src/physics/validation/pointSourceRules.ts, computed with ps2ff 1.5.9 (USGS,
public domain): single_event_adjustment with the parameters ShakeMap 4.0.2
passes for an origin with no tectonic region (shakelib/rupture/
point_rupture.py at that tag) — WC94, mechanism A, aspect ratio 1.7, dips
10° to 90° in four steps, nxny 7, nineteen azimuths, five epsilons truncated
at two — at rule 51's 49 epicentral distances, for a grid of magnitudes and
hypocentral depths. Writes src/physics/validation/ps2ffReference.ts. Nothing
here runs Nimbus.

    <python with numpy, scipy and ps2ff 1.5.9> scripts/benchmark/ps2ff-reference.py
"""

from importlib.metadata import version
from pathlib import Path

import numpy as np
from ps2ff.constants import MagScaling, Mechanism
from ps2ff.run import single_event_adjustment

ROOT = Path(__file__).resolve().parents[2]
MAGNITUDES = [5.0, 6.0, 6.7, 7.4]
DEPTHS_KM = [1.0, 5.0, 15.0, 33.0]


def main():
    lines = []
    for mag in MAGNITUDES:
        for depth in DEPTHS_KM:
            repi, rjb, rrup, _, _ = single_event_adjustment(
                mag,
                depth,
                ar=1.7,
                mechanism=Mechanism.A,
                mag_scaling=MagScaling.WC94,
                n_repi=49,
                min_repi=0.1,
                max_repi=1000,
                nxny=7,
                n_theta=19,
                n_dip=4,
                min_dip=10.0 * np.pi / 180.0,
                max_dip=90.0 * np.pi / 180.0,
                n_eps=5,
                trunc=2,
            )
            for r, a, b in zip(repi, rjb, rrup):
                lines.append(f"  [{mag}, {depth}, {float(r)!r}, {float(a)!r}, {float(b)!r}],")
    body = f"""// Generated by scripts/benchmark/ps2ff-reference.py with ps2ff {version("ps2ff")}
// (USGS, public domain), numpy {np.__version__}. Do not edit by hand.

/** ps2ff's single_event_adjustment for rule 51 of pointSourceRules.ts:
 *  [magnitude, hypocentral depth (km), epicentral distance (km), average
 *  Joyner–Boore distance (km), average rupture distance (km)]. */
// prettier-ignore
export const PS2FF_REFERENCE: readonly (readonly [number, number, number, number, number])[] = [
{chr(10).join(lines)}
];
"""
    out = ROOT / "src" / "physics" / "validation" / "ps2ffReference.ts"
    out.write_text(body)
    print(f"wrote {len(lines)} rows to {out}")


if __name__ == "__main__":
    main()
